package com.practiceproblems.convert_jsonobjectinarray;

public class Object {
    private String name;
    private int age;

    // Constructor
    public Object(String name, int age) {
        this.name = name;
        this.age = age;
    }
    // getters and setters
    public String getName() {
        return name;
    }
    public void setName(String name) {
        this.name = name;
    }
    public int getAge() {
        return age;
    }
    public void setAge(int age) {
        this.age = age;
    }
}
